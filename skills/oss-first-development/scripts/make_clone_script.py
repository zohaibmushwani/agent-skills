#!/usr/bin/env python3
"""make_clone_script.py - write clone-references.sh for the R/P repos of a shortlist.

Usage: python make_clone_script.py shortlist.json [--out clone-references.sh]
shortlist.json: [{"repo":"owner/name","label":"R","sparse":["crates/figma_import","docs"]}, ...]
  N-labelled repos are skipped. 'sparse' (optional) = only those folders are checked out.
Clones are shallow (depth 1) into references/<owner>__<name>/ (add references/ to .gitignore).
Read the real files there before adopting anything; respect each LICENSE.
"""
import json
import sys


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    items = json.load(open(argv[1], encoding="utf-8"))
    out = argv[argv.index("--out") + 1] if "--out" in argv else "clone-references.sh"
    L = ["#!/usr/bin/env bash", "# generated by make_clone_script.py - shallow clones for study (read-only references)",
         "set -u", 'mkdir -p references', 'fail=0']
    n = 0
    for it in items:
        if it.get("label", "P") == "N":
            continue
        repo = it["repo"].replace("github.com/", "")
        dest = "references/" + repo.replace("/", "__")
        n += 1
        if it.get("sparse"):
            L.append(f'[ -d "{dest}" ] || {{ git clone --depth 1 --filter=blob:none --sparse "https://github.com/{repo}.git" "{dest}" && '
                     f'git -C "{dest}" sparse-checkout set {" ".join(it["sparse"])}; }} || {{ echo "FAIL {repo}"; fail=1; }}')
        else:
            L.append(f'[ -d "{dest}" ] || git clone --depth 1 "https://github.com/{repo}.git" "{dest}" || {{ echo "FAIL {repo}"; fail=1; }}')
    L.append('echo "done ($fail = 1 means some clones failed)"; exit $fail')
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print(f"wrote {out} with {n} repos")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
